import { boolean, doublePrecision, index, integer, jsonb, smallint, text, time, timestamp, uniqueIndex, uuid, pgTable, type AnyPgColumn } from "drizzle-orm/pg-core";
import { id, timestamps, type I18nText } from "./_shared";
import { memberRoleEnum, planEnum, planStatusEnum, themeEnum } from "./enums";

export type RestaurantSettings = {
  /** Set when the owner finishes (or skips) the setup wizard. */
  onboardedAt?: string;
  seatingModes?: Array<"table" | "room" | "area" | "counter" | "takeaway" | "delivery">;
  qrStrategy?: "per_seat" | "generic";
  orderValidation?: "direct" | "server_confirms";
  enabledLocales?: string[];
  features?: Partial<Record<FeatureFlag, boolean>>;
  inactivity?: { warnAfterSec: number; releaseAfterSec: number };
  /** Secret in the personnel check-in QR (/pointage/<token>); regenerated by the owner. */
  attendanceToken?: string;
  /** Secret of the « Rejoindre l'équipe » QR (regenerable). */
  joinToken?: string;
  /**
   * A business created for someone (e.g. imported by the platform): the first person who signs
   * in with this verified email becomes its owner. Lower case; removed once claimed.
   */
  ownerEmail?: string;
  /**
   * Account recovery (verified by TIBLOGICS): the ownerEmail account replaces the current owner,
   * whose account is switched off (kept for history).
   */
  ownerTransfer?: boolean;
  /** Why the platform suspended this business (shown to the super admin). */
  suspendedReason?: string;
  /** Second brand colour (« couleur d’accent »): header band, « Nouveau » badges, titles. */
  accent2?: string;
  /** WhatsApp that receives takeaway orders when it is not the main WhatsApp (absent = same). */
  takeawayWhatsapp?: string;
  /** PIN sessions on authorised devices: end of shift (hours) and auto-lock when idle (minutes). */
  staffSessions?: { shiftHours: number; idleMinutes: number };
  /** Front desk timers: an open order turns orange, then red, after these many minutes. */
  serviceDelays?: { warnMin: number; lateMin: number };
};

export const FEATURE_FLAGS = ["welcomeScreen", "fortuneCookie", "takeawayWhatsapp", "share", "localBadge", "attendance"] as const;
export type FeatureFlag = (typeof FEATURE_FLAGS)[number];

export const restaurants = pgTable(
  "restaurants",
  {
    id: id(),
    /**
     * Multi-branch: a branch is a full restaurant pointing at its head restaurant.
     * Tenant scoping stays one restaurant_id everywhere.
     */
    parentRestaurantId: uuid("parent_restaurant_id").references((): AnyPgColumn => restaurants.id, { onDelete: "set null" }),
    slug: text("slug").notNull(),
    /** « restaurant » (tables, rooms…) or « transport » (VIP buses serving food on board). */
    kind: text("kind").$type<"restaurant" | "transport">().notNull().default("restaurant"),
    name: text("name").notNull(),
    /** Short presentation shown under the name on the public menu. */
    description: jsonb("description").$type<I18nText>(),
    legalName: text("legal_name"),
    logoUrl: text("logo_url"),
    coverUrl: text("cover_url"),
    theme: themeEnum("theme").notNull().default("warm"),
    accentColor: text("accent_color").notNull().default("#0F6B3E"),
    phones: text("phones").array().notNull().default([]),
    whatsapp: text("whatsapp"),
    orangeMoney: text("orange_money"),
    moovMoney: text("moov_money"),
    address: text("address"),
    city: text("city").notNull().default("Ouagadougou"),
    gmapsUrl: text("gmaps_url"),
    /**
     * Business location (customers' « Itinéraire », the platform map). Saved from the owner's phone
     * GPS (on site, after a warning) or read from a Google Maps link. WGS84 degrees.
     */
    latitude: doublePrecision("latitude"),
    longitude: doublePrecision("longitude"),
    /** GPS accuracy in metres when saved from the phone; null for a link. */
    locationAccuracyM: integer("location_accuracy_m"),
    locationSource: text("location_source").$type<"gps" | "link">(),
    locationSetAt: timestamp("location_set_at", { withTimezone: true }),
    timezone: text("timezone").notNull().default("Africa/Ouagadougou"),
    defaultLocale: text("default_locale").notNull().default("fr"),
    settings: jsonb("settings").$type<RestaurantSettings>().notNull().default({}),
    plan: planEnum("plan").notNull().default("pro"),
    planStatus: planStatusEnum("plan_status").notNull().default("trial"),
    planExpiresAt: timestamp("plan_expires_at", { withTimezone: true }),
    published: boolean("published").notNull().default(false),
    poweredBadge: boolean("powered_badge").notNull().default(true),
    /** Shown on restocool.com (1 = first). Set by the platform admin; null = not featured. */
    /** Deleted at the owner's request (confirmed by RestoCool): offline, team closed, restorable 10 days. */
    deletedAt: timestamp("deleted_at", { withTimezone: true }),
    featuredRank: smallint("featured_rank"),
    ...timestamps,
  },
  (t) => [uniqueIndex("restaurants_slug_uq").on(t.slug), index("restaurants_parent_idx").on(t.parentRestaurantId)],
);

/**
 * Job roles of a restaurant (« Serveur·se », « Aide-cuisinier·ère », or one the owner typed in)
 * and the access areas each one opens (see src/lib/auth/access.ts). Catalog roles have a `key`
 * (translated name); custom roles have a `name`.
 */
export const jobRoles = pgTable(
  "job_roles",
  {
    id: id(),
    restaurantId: uuid("restaurant_id").notNull().references(() => restaurants.id, { onDelete: "cascade" }),
    key: text("key"),
    name: text("name"),
    group: text("group").notNull().default("front"),
    access: text("access").array().notNull().default([]),
    sort: integer("sort").notNull().default(0),
    ...timestamps,
  },
  (t) => [index("job_roles_restaurant_idx").on(t.restaurantId), uniqueIndex("job_roles_restaurant_key_uq").on(t.restaurantId, t.key)],
);

/**
 * Who can sign in to which restaurant, and with which RestoCool role.
 * App-managed tenants: Clerk only proves identity (clerk_user_id); restaurant
 * membership lives here, not in Clerk Organizations.
 */
export const members = pgTable(
  "members",
  {
    id: id(),
    restaurantId: uuid("restaurant_id").notNull().references(() => restaurants.id, { onDelete: "cascade" }),
    /** Null for personnel without an email (they use their matricule + PIN). */
    clerkUserId: text("clerk_user_id"),
    email: text("email"),
    name: text("name"),
    /** Phone (+226…), given when the person joined with the team QR. */
    phone: text("phone"),
    role: memberRoleEnum("role").notNull().default("manager"),
    /** The person's job role; its access replaces the level's defaults. Null = level defaults. */
    jobRoleId: uuid("job_role_id").references((): AnyPgColumn => jobRoles.id, { onDelete: "set null" }),
    active: boolean("active").notNull().default(true),
    /**
     * « Matricule »: the person's staff number in this restaurant (1, 2, 3… shown as 001),
     * never reused. Orders record it for every step they handle.
     */
    staffNo: integer("staff_no"),
    /** 4–6 digit PIN (scrypt hash) for check-in and, later, PIN login on the restaurant tablet. */
    pinHash: text("pin_hash"),
    pinFailures: smallint("pin_failures").notNull().default(0),
    lockedUntil: timestamp("locked_until", { withTimezone: true }),
    /** Left the business: no access any more, kept in « Anciens employés » with their history. */
    archivedAt: timestamp("archived_at", { withTimezone: true }),
    archivedReason: text("archived_reason"),
    /** Personal data erased on request (name, phone, email, PIN, login); matricule and history kept. */
    erasedAt: timestamp("erased_at", { withTimezone: true }),
    /** Last time this person used the app (updated at most every 5 minutes), for activity ranking. */
    lastSeenAt: timestamp("last_seen_at", { withTimezone: true }),
    ...timestamps,
  },
  (t) => [
    index("members_restaurant_idx").on(t.restaurantId),
    uniqueIndex("members_restaurant_staff_no_uq").on(t.restaurantId, t.staffNo),
    index("members_user_idx").on(t.clerkUserId),
    uniqueIndex("members_restaurant_user_uq").on(t.restaurantId, t.clerkUserId),
  ],
);

export const openingHours = pgTable(
  "opening_hours",
  {
    id: id(),
    restaurantId: uuid("restaurant_id").notNull().references(() => restaurants.id, { onDelete: "cascade" }),
    /** 0 = Sunday … 6 = Saturday */
    weekday: smallint("weekday").notNull(),
    opens: time("opens").notNull(),
    /** May be earlier than `opens` when service runs past midnight. */
    closes: time("closes").notNull(),
    ...timestamps,
  },
  (t) => [index("opening_hours_restaurant_idx").on(t.restaurantId)],
);
